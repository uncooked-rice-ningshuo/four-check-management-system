   const limited=kind==='class'?{classId:fixture.class}:{grade:'2026级'}
   for(const action of ['INSPECTION_VIEW','INSPECTION_ENTER']) await request(admin,token,'/admin/users/'+account.id+'/permission-rules','POST',{action,effect:'ALLOW',scope:{inspectionTypeId:options.inspectionTypeId,departmentId:dorm.id,...limited},enabled:true,note:'isolated scoped import'},201)
   const access=(await(await request(c,'','/auth/login','POST',{loginName:name,password:fixture.authPassword})).json()).accessToken
   const p=await c.newPage()
   await p.goto(base+'/inspections/dormitory-hygiene')
   await p.getByRole('button',{name:'批量导入宿舍卫生',exact:true}).click()
