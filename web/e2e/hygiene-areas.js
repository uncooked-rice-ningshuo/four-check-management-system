async (page) => {
  const fixture = __FIXTURE__, output = __OUTPUT__
  const origin = page.url().split('/').slice(0, 3).join('/')
  const cases = [], browserErrors = [], contexts = []
  const check = (ok, message) => { if (!ok) throw new Error(message) }
  page.on('pageerror', error => browserErrors.push(error.message))
  const request = async (context, token, path, method = 'GET', data, status = 200) => {
    const response = await context.request.fetch(origin + '/api/v1' + path, { method, data, headers: token ? { Authorization: 'Bearer ' + token } : {} })
    check(response.status() === status, `${method} ${path.split('?')[0]} expected ${status}, got ${response.status()}`)
    return response
  }
  const context = async () => { const item = await page.context().browser().newContext(); contexts.push(item); return item }
  const choose = async (scope, name, text) => {
    await scope.getByRole('combobox', { name: new RegExp(name + '$') }).click()
    await page.locator('.ant-select-dropdown:visible .ant-select-item-option').filter({ hasText: text }).first().click()
  }
  const close = async () => { const drawer = page.getByRole('dialog'); await drawer.getByRole('button', { name: 'Close', exact: true }).click(); await drawer.waitFor({ state: 'hidden' }) }
  const row = name => page.getByRole('row').filter({ has: page.getByRole('cell', { name, exact: true }) })
  try {
    const admin = await context()
    const token = (await (await request(admin, '', '/auth/login', 'POST', { loginName: 'browser-admin', password: fixture.authPassword })).json()).accessToken
    const targets = await (await request(admin, token, '/admin/hygiene-areas/options')).json()
    const classroom = targets.find(item => item.kind === 'classroom-hygiene-areas')
    const publicArea = targets.find(item => item.kind === 'public-dormitory-hygiene-areas')
    check(classroom && publicArea, 'Configured hygiene target missing')
    const base = target => '/admin/hygiene-areas/' + target.kind
    const url = target => base(target) + '?departmentId=' + target.departmentId
    await request(admin, '', url(classroom), 'GET', undefined, 401)
    await request(admin, token, url(classroom), 'POST', { name: '无关联区域' }, 400)
    const menu = page.locator('#admin-navigation .ant-menu-submenu:not(.ant-menu-submenu-open) > .ant-menu-submenu-title').filter({ hasText: '系统配置' })
    if (await menu.count()) await menu.click()
    await page.getByRole('link', { name: '卫生区域维护', exact: true }).click()
    await page.getByRole('heading', { name: '卫生区域维护' }).waitFor()
    for (const [target, field, parent, floor] of [[classroom, '教室', 'E2E building 101', ''], [publicArea, '宿舍楼', 'E2E dorm building', '一层']]) {
      await choose(page, '维护范围', target.inspectionTypeName + ' · ' + target.departmentName)
      await page.getByRole('button', { name: '新增区域' }).click()
      let drawer = page.getByRole('dialog', { name: '新增卫生区域' })
      await choose(drawer, field, parent)
      if (floor) await drawer.getByLabel('楼层/单元').fill(floor)
      await drawer.getByLabel('区域名称').fill('回归区域 A')
      await drawer.getByRole('button', { name: /保\s*存/ }).click()
      await drawer.waitFor({ state: 'hidden' })
      const label = [parent, floor, '回归区域 A'].filter(Boolean).join(' / ')
      await row(label).waitFor()
      await page.getByRole('button', { name: '新增区域' }).click()
      drawer = page.getByRole('dialog', { name: '新增卫生区域' })
      await choose(drawer, field, parent)
      if (floor) await drawer.getByLabel('楼层/单元').fill(floor)
      await drawer.getByLabel('区域名称').fill('第二测试区域')
      await drawer.getByRole('button', { name: /保\s*存/ }).click()
      await drawer.waitFor({ state: 'hidden' })
      const secondLabel = [parent, floor, '第二测试区域'].filter(Boolean).join(' / ')
      await row(secondLabel).getByRole('button', { name: '编辑', exact: true }).click()
      drawer = page.getByRole('dialog', { name: '编辑卫生区域' })
      check(await drawer.getByLabel('区域名称').inputValue() === '第二测试区域', 'Second record lost name')
      await close()
      await row(label).getByRole('button', { name: '编辑', exact: true }).click()
      drawer = page.getByRole('dialog', { name: '编辑卫生区域' })
      check(await drawer.getByLabel('区域名称').inputValue() === '回归区域 A', 'First edit lost name')
      await close()
      await page.getByRole('button', { name: '新增区域' }).click()
      await close()
      await row(label).getByRole('button', { name: '编辑', exact: true }).click()
      drawer = page.getByRole('dialog', { name: '编辑卫生区域' })
      check(await drawer.getByLabel('区域名称').inputValue() === '回归区域 A', 'Create-close-edit lost name')
      await drawer.getByLabel('区域名称').fill('回归区域 B')
      const fail = route => route.request().method() === 'PUT' ? route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ code: 'INTERNAL_ERROR', message: '操作失败' }) }) : route.continue()
      const pattern = '**/api/v1/admin/hygiene-areas/' + target.kind + '/*'
      await page.route(pattern, fail)
      await drawer.getByRole('button', { name: /保\s*存/ }).click()
      await drawer.getByText('保存失败，请检查输入或权限后重试', { exact: true }).waitFor()
      check(await drawer.getByLabel('区域名称').inputValue() === '回归区域 B', 'Failed save lost input')
      await page.unroute(pattern, fail)
      await drawer.getByRole('button', { name: /保\s*存/ }).click()
      await drawer.waitFor({ state: 'hidden' })
      const updatedLabel = [parent, floor, '回归区域 B'].filter(Boolean).join(' / ')
      await row(updatedLabel).waitFor()
      await row(updatedLabel).getByRole('button', { name: '编辑', exact: true }).click()
      drawer = page.getByRole('dialog', { name: '编辑卫生区域' })
      check(await drawer.getByLabel('区域名称').inputValue() === '回归区域 B', 'Saved name not restored')
      await close()
      await row(updatedLabel).getByRole('button', { name: '停用', exact: true }).click()
      const confirm = page.getByRole('dialog', { name: '停用此区域？' })
      await confirm.getByRole('button', { name: /确\s*定|OK/ }).click()
      await confirm.waitFor({ state: 'hidden' })
      await row(updatedLabel).getByRole('cell', { name: '停用', exact: true }).waitFor()
      await row(updatedLabel).getByRole('button', { name: '变更记录' }).click()
      const history = page.getByRole('dialog', { name: '区域变更记录' })
      await history.getByRole('cell', { name: 'CREATE', exact: true }).waitFor()
      check(await history.getByRole('cell', { name: 'UPDATE', exact: true }).count() === 2, 'Change history missing updates')
      await close()
      const stored = (await (await request(admin, token, url(target))).json()).items.find(item => item.name === '回归区域 B')
      check(stored && !stored.enabled, 'Disabled area did not persist')
      const duplicate = await request(admin, token, url(target), 'POST', { ...stored, enabled: true }, 409)
      check((await duplicate.json()).code === 'MASTER_DATA_NAME_EXISTS', 'Duplicate area lacks stable error code')
      const invalidParent = target.kind === 'classroom-hygiene-areas' ? { classroomId: fixture.dormBuilding } : { dormitoryBuildingId: fixture.room, floorUnit: '1' }
      const invalidRelation = await request(admin, token, url(target), 'POST', { name: '错误关联', ...invalidParent }, 400)
      check((await invalidRelation.json()).code === 'INVALID_REQUEST', 'Invalid parent lacks stable error code')
      const changes = await (await request(admin, token, base(target) + '/' + stored.id + '/changes?departmentId=' + target.departmentId)).json()
      check(changes.length === 3, 'Database history missing')
      cases.push(target.inspectionTypeName + '真实新增/A与B回显/新增关闭后编辑/500重试/停用/重复409与无效关联400/变更历史')
    }
    const catalogs = await (await request(admin, '', '/public/registration-options')).json()
    const role = catalogs.organizationRoles.find(item => item.code === 'MEMBER')
    const globalAdmin = await context()
    const globalAccount = await (await request(globalAdmin, '', '/auth/register', 'POST', { studentNo: 'area-global', name: '全局基础数据测试', password: fixture.matrixPassword, requestedDepartmentId: classroom.departmentId, requestedOrgRoleId: role.id }, 201)).json()
    await request(admin, token, '/admin/registration-requests/' + globalAccount.id + '/review', 'POST', { decision: 'APPROVE', reason: 'isolated global area regression' })
    await request(admin, token, '/admin/users/' + globalAccount.id, 'PUT', { studentNo: 'area-global', name: '全局基础数据测试', systemRole: 'ADMIN' })
    const globalToken = (await (await request(globalAdmin, '', '/auth/login', 'POST', { loginName: 'area-global', password: fixture.matrixPassword })).json()).accessToken
    check((await (await request(globalAdmin, globalToken, '/admin/hygiene-areas/options')).json()).length === targets.length, 'Global administrator lost mapped targets')
    await request(globalAdmin, globalToken, url(publicArea), 'POST', { name: '全局维护区域', dormitoryBuildingId: fixture.dormBuilding, floorUnit: '2' }, 201)
    const globalPage = await globalAdmin.newPage()
    await globalPage.goto(origin + '/admin/hygiene-areas')
    await globalPage.getByRole('button', { name: '新增区域' }).waitFor()
    await globalPage.getByRole('link', { name: '卫生区域维护', exact: true }).waitFor()
    cases.push('系统管理员保留全部已配置维护目标、真实创建与页面访问')
    const member = await context()
    const account = await (await request(member, '', '/auth/register', 'POST', { studentNo: 'area-scoped', name: '区域授权测试', password: fixture.matrixPassword, requestedDepartmentId: classroom.departmentId, requestedOrgRoleId: role.id }, 201)).json()
    await request(admin, token, '/admin/registration-requests/' + account.id + '/review', 'POST', { decision: 'APPROVE', reason: 'isolated area regression' })
    await request(admin, token, '/admin/users/' + account.id + '/permission-rules', 'POST', { action: 'MASTER_DATA_MANAGE', effect: 'ALLOW', scope: { departmentId: classroom.departmentId, inspectionTypeId: classroom.inspectionTypeId }, enabled: true, note: 'isolated area grant' }, 201)
    const memberToken = (await (await request(member, '', '/auth/login', 'POST', { loginName: 'area-scoped', password: fixture.matrixPassword })).json()).accessToken
    const memberTargets = await (await request(member, memberToken, '/admin/hygiene-areas/options')).json()
    check(memberTargets.length === 1 && memberTargets[0].kind === classroom.kind, 'Scoped grant leaked target')
    const memberPage = await member.newPage()
    await memberPage.goto(origin + '/admin/hygiene-areas')
    await memberPage.getByRole('link', { name: '卫生区域维护', exact: true }).waitFor()
    await memberPage.getByRole('button', { name: '新增区域' }).waitFor()
    check(await memberPage.getByRole('link', { name: '基础数据', exact: true }).count() === 0, 'Scoped role exposes general catalog')
    await request(member, memberToken, '/admin/master-data/classrooms', 'GET', undefined, 403)
    await request(member, memberToken, url(publicArea), 'POST', { name: '越权区域', dormitoryBuildingId: fixture.dormBuilding, floorUnit: '1' }, 403)
    const created = await (await request(member, memberToken, url(classroom), 'POST', { name: '部门维护区域', classroomId: fixture.room }, 201)).json()
    check(created.classroomId === fixture.room, 'Scoped create lost parent')
    cases.push('受限成员有维护入口和单一目标、真实创建成功，通用基础数据和其他检查类型写入403')
    await request(admin, token, '/admin/users/' + account.id + '/permission-rules', 'POST', { action: 'MASTER_DATA_MANAGE', effect: 'DENY', scope: { departmentId: classroom.departmentId }, enabled: true, note: 'isolated area denial' }, 201)
    const deniedToken = (await (await request(member, '', '/auth/login', 'POST', { loginName: 'area-scoped', password: fixture.matrixPassword })).json()).accessToken
    check((await (await request(member, deniedToken, '/admin/hygiene-areas/options')).json()).length === 0, 'DENY targets not empty')
    await request(member, deniedToken, base(classroom) + '/' + created.id + '?departmentId=' + classroom.departmentId, 'PUT', { ...created, name: '越权修改' }, 403)
    await memberPage.reload()
    await memberPage.getByText('当前账号没有卫生区域维护权限', { exact: true }).waitFor()
    check(await memberPage.getByRole('link', { name: '卫生区域维护', exact: true }).count() === 0, 'DENY navigation leaked')
    cases.push('实时DENY阻止修改，重新登录后入口隐藏及直达无权限')
    const malformed = route => route.fulfill({ status: 200, contentType: 'application/json', body: '{}' })
    const targetPattern = '**/api/v1/admin/hygiene-areas/options'
    await page.route(targetPattern, malformed)
    await page.reload()
    await page.getByText('区域配置加载失败，请重试', { exact: true }).waitFor()
    check(await page.getByText('当前账号没有卫生区域维护权限', { exact: true }).count() === 0, 'Malformed response shown as no permission')
    await page.unroute(targetPattern, malformed)
    await page.getByRole('button', { name: /重\s*试/ }).click()
    await page.getByRole('button', { name: '新增区域' }).waitFor()
    cases.push('200异常选项响应明确失败，恢复后可重试')
    await page.setViewportSize({ width: 390, height: 844 })
    await page.waitForFunction(() => document.querySelector('aside')?.getBoundingClientRect().width <= 81)
    const width = await page.evaluate(() => ({ page: document.documentElement.scrollWidth, viewport: innerWidth }))
    check(width.page <= width.viewport + 2, 'Area page overflows mobile viewport')
    check(await page.locator('.ant-table-content').first().evaluate(node => { node.scrollLeft = 500; return node.scrollLeft > 0 }), 'Area table cannot scroll')
    await page.screenshot({ path: output + '/hygiene-areas-mobile.png', fullPage: true })
    cases.push('390px窄屏与表格内横向滚动')
    check(browserErrors.length === 0, 'Browser runtime error')
    return { cases, browserErrors, browserVersion: page.context().browser().version(), faultInjection: ['区域PUT 500', '区域授权选项200异常响应'] }
  } finally { for (const item of contexts.reverse()) await item.close() }
}
