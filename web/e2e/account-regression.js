async (page) => {
  const fixture = __FIXTURE__
  const base = page.url().split('/').slice(0,3).join('/')
  const cases = []
  const context = await page.context().browser().newContext()
  const member = await context.newPage()
  const login = async () => {
    await member.goto(base + '/login')
    await member.getByRole('textbox', { name:'账号',exact:true }).fill('e2e-member')
    await member.getByLabel('密码',{exact:true}).fill(fixture.memberPassword)
    const [response] = await Promise.all([member.waitForResponse(r => r.url().endsWith('/api/v1/auth/login') && r.request().method() === 'POST'), member.getByRole('button',{name:/登\s*录/}).click()])
    return response
  }
  try {
    await member.goto(base + '/register')
    for (const [label,value] of [['学号','e2e-member'],['姓名','E2E member'],['密码',fixture.memberPassword],['确认密码',fixture.memberPassword]]) await member.getByLabel(label,{exact:true}).fill(value)
    for (const [label,value] of [['申请部门','学习部'],['申请角色','部门委员']]) {
      await member.getByRole('combobox',{name:label,exact:true}).click()
      await member.locator('.ant-select-dropdown:visible').getByText(value,{exact:true}).click()
    }
    await member.getByRole('checkbox').check()
    await member.getByRole('button',{name:'注册账号',exact:true}).click()
    await member.waitForURL('**/register/result')
    const pending = await login()
    if (pending.status() !== 401 || (await pending.json()).code !== 'INVALID_CREDENTIALS') throw new Error('Pending account was not rejected by API')
    await member.getByText('账号或密码错误，或账号尚未启用',{exact:true}).waitFor()
    if (!member.url().endsWith('/login')) throw new Error('Pending user entered protected page')
    cases.push('真实注册、待审核用户拒绝登录')
    await page.goto(base + '/admin/registrations')
    await page.getByRole('row').filter({hasText:'E2E member'}).getByRole('button',{name:/通\s*过/}).click()
    await page.getByRole('row').filter({hasText:'E2E member'}).waitFor({state:'hidden'})
    if ((await login()).status() !== 200) throw new Error('Approved account could not log in')
    await member.getByRole('heading',{name:'工作台',exact:true}).waitFor()
    await member.goto(base + '/admin/users')
    await member.waitForURL(base + '/')
    if (await member.getByRole('heading',{name:'用户与角色',exact:true}).count()) throw new Error('Member accessed user management')
    cases.push('管理员审核通过、普通成员登录工作台、管理路由越权拦截')
    await page.goto(base + '/admin/users')
    await page.locator('input[placeholder^="输入账号"]').fill('e2e-member')
    await page.getByRole('button',{name:/查\s*询/}).click()
    const row = page.getByRole('row').filter({hasText:'E2E member'})
    await row.getByRole('button',{name:'编辑',exact:true}).click()
    let editor = page.locator('.ant-modal:visible').filter({hasText:'编辑用户'})
    if (await editor.getByLabel('学号/登录账号').inputValue() !== 'e2e-member' || await editor.getByLabel('姓名').inputValue() !== 'E2E member') throw new Error('First edit did not populate account fields')
    await editor.getByRole('button',{name:/取\s*消/}).click()
    await page.getByRole('button',{name:'新增用户',exact:true}).click()
    await page.locator('.ant-modal:visible').filter({hasText:'新增用户'}).getByRole('button',{name:/取\s*消/}).click()
    await row.getByRole('button',{name:'编辑',exact:true}).click()
    editor = page.locator('.ant-modal:visible').filter({hasText:'编辑用户'})
    if (await editor.getByLabel('学号/登录账号').inputValue() !== 'e2e-member' || await editor.getByLabel('姓名').inputValue() !== 'E2E member') throw new Error('Create-close-edit did not populate account fields')
    await editor.getByRole('button',{name:/取\s*消/}).click()
    cases.push('用户编辑首次回显与新增关闭后再次回显')
    if (await row.locator('.user-assignment-tag').count() !== 2) throw new Error('Department and organization role tags are missing')
    await row.getByRole('button',{name:'重置密码',exact:true}).click()
    await page.locator('.ant-modal:visible').filter({hasText:'重置 E2E member 的密码'}).getByRole('button',{name:/确\s*定/}).click()
    const result = page.locator('.ant-modal:visible').filter({hasText:'密码重置成功'})
    await result.getByText('登录账号',{exact:true}).waitFor()
    if (await result.getByText('e2e-member',{exact:true}).count() !== 1 || (await result.locator('.issued-password-details code').innerText()).length < 12) throw new Error('Reset credential was not shown to the administrator')
    await result.getByRole('button',{name:'我已记录并告知用户'}).click()
    cases.push('部门和组织角色标签、重置后账号及初始密码一次性提示')
    await row.getByRole('button',{name:/禁\s*用/}).click()
    await page.locator('.ant-popconfirm').getByRole('button',{name:/确\s*定|确认/}).click()
    await row.getByText('已禁用',{exact:true}).waitFor()
    await member.goto(base + '/')
    await member.waitForURL('**/login')
    cases.push('禁用用户后既有会话失效')
  } finally { await context.close() }
  return { cases }
}
