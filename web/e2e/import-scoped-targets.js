  await attendance.locator('input[type=file]').setInputFiles(fixture.attendanceInvalidFile)
  const [reupload]=await Promise.all([page.waitForResponse(r=>r.request().method()==='POST'&&r.url().endsWith('/imports/attendance')),attendance.getByRole('button',{name:'上传并生成预览'}).click()])
