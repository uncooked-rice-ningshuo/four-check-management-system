   const label=kind==='class'?'导入目标班级':'导入目标年级'
   check(await drawer.getByRole('combobox',{name:label,exact:true}).count()===1,kind+': template returned 403 but no independent target selector exists')
   await drawer.getByRole('combobox',{name:label,exact:true}).click()
   await p.locator('.ant-select-dropdown:visible .ant-select-item-option-content').getByText(kind==='class'?'E2E class':'2026级',{exact:true}).click()
