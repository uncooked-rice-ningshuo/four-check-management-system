async (page) => {
  const fixture = __FIXTURE__
  const output = __OUTPUT__
  const base = page.url().split('/').slice(0, 3).join('/')
  const cases = []
  const failures = []
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('response', r => { if (r.url().includes('/api/v1/') && r.status() >= 400) failures.push(`${r.status()} ${r.url().split('?')[0].split('/').slice(3).join('/').replace(/^/, '/')}`) })
  for (const [path, heading] of [['registrations','注册申请'],['users','用户与角色'],['organization','组织与业务'],['master-data','基础数据'],['dictionaries','字典管理'],['profile','个人信息'],['security','账户安全']]) {
    await page.goto(`${base}/admin/${path}`)
    await page.getByRole('heading', { name:heading, exact:true }).waitFor()
    await page.waitForLoadState('networkidle')
    cases.push(`${heading}真实页面/API 加载`)
  }
  await page.goto(base + '/admin/users')
  const navigation = page.locator('#admin-navigation')
  for (const group of ['基础功能','系统配置','日常检查']) await navigation.getByText(group,{exact:true}).waitFor()
  for (const group of ['基础功能','系统配置','日常检查']) {
    const parent = navigation.getByText(group,{exact:true}).locator('xpath=ancestor::li[contains(@class,"ant-menu-submenu")]')
    if (!(await parent.getAttribute('class')).includes('ant-menu-submenu-open')) await navigation.getByText(group,{exact:true}).click()
    await page.waitForFunction(groupName => {
      const opened = [...document.querySelectorAll('#admin-navigation .ant-menu-submenu-open')]
      return opened.length === 1 && opened[0].querySelector('.ant-menu-submenu-title')?.textContent?.includes(groupName)
    }, group)
    await page.waitForFunction(() => !document.querySelector('#admin-navigation .ant-motion-collapse'))
    const menuWidths = await navigation.locator('.ant-menu-item, .ant-menu-submenu-title').evaluateAll(items => items.filter(item => item.getClientRects().length && getComputedStyle(item).visibility !== 'hidden').map(item => {
    const link = item.querySelector('a') ?? item.querySelector('.ant-menu-title-content')
    const bounds = item.getBoundingClientRect()
    const range = document.createRange()
    if (link) range.selectNodeContents(link)
    return { text:link?.textContent ?? '', clipped:item.scrollWidth > item.clientWidth + 1 || (link && range.getBoundingClientRect().right > bounds.right - 4) }
    }))
    if (menuWidths.some(item => item.clipped)) throw new Error('Expanded sidebar clips menu text: ' + menuWidths.filter(item => item.clipped).map(item => item.text).join(','))
  }
  const scrollbarWidth = await navigation.locator('.ant-menu-root').evaluate(menu => getComputedStyle(menu).scrollbarWidth)
  if (scrollbarWidth !== 'none') throw new Error('Sidebar scrollbar remains visible during expansion')
  await page.screenshot({path:`${output}/sidebar-expanded.png`})
  await page.getByRole('button',{name:'收起侧边栏'}).click()
  await page.waitForFunction(() => Math.abs(document.querySelector('#admin-navigation').getBoundingClientRect().width - 80) < 1)
  const collapsedIconOffsets = await navigation.locator('.ant-menu-root > .ant-menu-item, .ant-menu-root > .ant-menu-submenu > .ant-menu-submenu-title').evaluateAll(items => items.map(item => {
    const icon = item.querySelector('.ant-menu-item-icon')
    if (!icon) return null
    const itemBounds = item.getBoundingClientRect()
    const iconBounds = icon.getBoundingClientRect()
    return { text: item.textContent, x: Math.abs((itemBounds.left + itemBounds.right - iconBounds.left - iconBounds.right) / 2), y: Math.abs((itemBounds.top + itemBounds.bottom - iconBounds.top - iconBounds.bottom) / 2) }
  }).filter(Boolean))
  if (collapsedIconOffsets.some(item => item.x > 2 || item.y > 2)) throw new Error('Collapsed sidebar icons are off-center: ' + JSON.stringify(collapsedIconOffsets))
  await page.screenshot({path:`${output}/sidebar-collapsed.png`})
  await page.getByRole('button',{name:'展开侧边栏'}).click()
  await page.waitForFunction(() => Math.abs(document.querySelector('#admin-navigation').getBoundingClientRect().width - 256) < 1)
  const closedInspection = navigation.locator('.ant-menu-submenu:not(.ant-menu-submenu-open) > .ant-menu-submenu-title').filter({hasText:'日常检查'})
  if (await closedInspection.count()) await closedInspection.click()
  if (await navigation.getByRole('link',{name:'无机课堂检查'}).count() !== 1) throw new Error('Expanded sidebar lost inspection navigation')
  await navigation.getByRole('link',{name:'工作台'}).click()
  if (await navigation.locator('.ant-menu-submenu-open').count()) throw new Error('Workbench navigation left a parent expanded')
  await navigation.getByText('日常检查',{exact:true}).click()
  await navigation.getByRole('link',{name:'到课率检查'}).click()
  await page.getByRole('heading',{name:'到课率检查',exact:true}).waitFor()
  await navigation.getByRole('link',{name:'工作台'}).click()
  await page.getByRole('heading',{name:'工作台',exact:true}).waitFor()
  if (await navigation.locator('.ant-menu-submenu-open').count()) throw new Error('Workbench did not collapse the selected child menu on return')
  cases.push('工作台独立入口、一级菜单互斥展开、展开时滚动条隐藏及文字完整显示')
  await page.goto(base + '/admin/master-data')
  for (const name of ['年级','院系','专业','班级','教职工/班主任','学生','宿舍','宿舍区','宿舍楼','教学楼','教室','课程']) {
    await page.getByRole('menuitem', { name, exact:true }).click()
    await page.waitForLoadState('networkidle')
  }
  cases.push('十二类基础数据列表及关联选项真实加载')
  await page.goto(base + '/admin/dictionaries')
  await page.getByRole('button', { name:'新增字典类型',exact:true }).click()
  let dialog = page.getByRole('dialog', { name:'新增字典类型',exact:true })
  await dialog.getByLabel('类型编码').fill('E2E_TYPE')
  await dialog.getByLabel('类型名称').fill('E2E dictionary')
  await dialog.getByRole('button', { name:/确\s*定/ }).click()
  await dialog.waitFor({state:'hidden'})
  const dictionary = page.getByRole('row').filter({hasText:'E2E_TYPE'})
  await dictionary.getByRole('radio').check()
  await page.getByRole('button', {name:'新增选项',exact:true}).click()
  dialog = page.getByRole('dialog', {name:'新增字典项',exact:true})
  await dialog.getByLabel('选项值').fill('E2E_VALUE')
  await dialog.getByLabel('显示名称').fill('E2E option')
  await dialog.getByRole('button', {name:/确\s*定/}).click()
  await dialog.waitFor({state:'hidden'})
  await page.getByRole('row').filter({hasText:'E2E_VALUE'}).getByRole('button',{name:'编辑',exact:true}).click()
  dialog = page.getByRole('dialog',{name:'编辑字典项',exact:true})
  if (await dialog.getByLabel('显示名称').inputValue() !== 'E2E option') throw new Error('Dictionary first edit lost value')
  await dialog.getByLabel('显示名称').fill('E2E option edited')
  await dialog.getByRole('button',{name:/确\s*定/}).click()
  await dialog.waitFor({state:'hidden'})
  await page.getByRole('cell',{name:'E2E option edited',exact:true}).waitFor()
  cases.push('字典类型/选项真实新建、首次编辑回显及保存')
  await page.goto(base + '/admin/master-data')
  await page.getByRole('menuitem',{name:'院系',exact:true}).click()
  await page.getByRole('button',{name:'新增院系',exact:true}).click()
  dialog = page.getByRole('dialog',{name:'新增院系',exact:true})
  await dialog.getByLabel('名称').fill('E2E created faculty')
  // Wait after typing, never before: completion of opening animation must not reset user input.
  await dialog.evaluate(element => Promise.all(element.getAnimations({ subtree:true }).map(animation => animation.finished)))
  if (await dialog.getByLabel('名称').inputValue() !== 'E2E created faculty') throw new Error('Opening animation erased early input')
  await dialog.getByRole('button',{name:/确\s*定/}).click()
  await dialog.waitFor({state:'hidden'})
  await page.getByRole('row').filter({hasText:'E2E created faculty'}).getByRole('button',{name:'编辑',exact:true}).click()
  dialog = page.getByRole('dialog',{name:'编辑院系',exact:true})
  await dialog.getByLabel('名称').waitFor()
  if (await dialog.getByLabel('名称').inputValue() !== 'E2E created faculty') throw new Error('Master data first edit lost value')
  await dialog.getByLabel('名称').fill('E2E faculty edited')
  await dialog.getByRole('button',{name:/确\s*定/}).click()
  await dialog.waitFor({state:'hidden'})
  await page.getByRole('cell',{name:'E2E faculty edited',exact:true}).waitFor()
  cases.push('基础数据院系真实新建、首次编辑回显及保存')
  await page.goto(base + '/')
  await page.getByRole('region', { name:'当前工作上下文' }).waitFor()
  await page.getByRole('button', { name:'设置临时工作周' }).click()
  await page.getByRole('combobox', { name:'目标周次' }).click()
  await page.locator('.ant-select-dropdown:visible .ant-select-item-option').filter({hasText:'第 2 周'}).first().click()
  await page.getByLabel('到期时间（北京时间）').fill(fixture.expiry.replace('T',' '))
  await page.getByLabel('到期时间（北京时间）').press('Enter')
  await page.getByRole('textbox', { name:'覆盖原因' }).fill('E2E override')
  await page.getByRole('button', { name:'确认全局覆盖' }).click()
  await page.getByText(/当前工作周：第 2 周/).waitFor()
  await page.reload()
  await page.getByText(/当前工作周：第 2 周/).waitFor()
  await page.getByRole('button', { name:'设置临时工作周' }).click()
  await page.getByRole('textbox', { name:'覆盖原因' }).fill('E2E restore')
  await page.getByRole('button', { name:'恢复校历', exact:true }).click()
  await page.getByText(/当前工作周：第 3 周/).waitFor()
  cases.push('工作台真实加载、临时工作周设置/重载/恢复校历')
  await page.setViewportSize({ width:390,height:844 })
  await page.goto(base + '/inspections/attendance')
  await page.getByRole('heading', { name:'到课率检查',exact:true }).waitFor()
  await page.screenshot({ path:`${output}/attendance-mobile.png`,fullPage:true })
  const layout = await page.evaluate(() => ({ viewport:innerWidth,width:document.documentElement.scrollWidth }))
  if (layout.width > layout.viewport) throw new Error('Page overflows narrow viewport')
  const scroll = await page.locator('.attendance-records-table .ant-table-content').evaluate(element => { element.scrollLeft = 400; return { offset:element.scrollLeft, width:element.scrollWidth, viewport:element.clientWidth } })
  if (scroll.width <= scroll.viewport || scroll.offset <= 0) throw new Error('Wide table cannot scroll inside its container')
  cases.push('390px 窄屏页面无横向溢出、表格可独立横向滚动')
  await page.setViewportSize({ width:1440,height:1000 })
  if (errors.length || failures.length) throw new Error(JSON.stringify({errors,failures}))
  return { cases, browserErrors:errors, narrowScreen:layout, tableScroll:scroll, limitations:['管理页面为加载覆盖，未代替全部管理动作及角色矩阵验收'] }
}
