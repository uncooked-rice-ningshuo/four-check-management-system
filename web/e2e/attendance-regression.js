async (page) => {
  const fixture = __FIXTURE__
  const output = __OUTPUT__
  const base = page.url().split('/').slice(0, 3).join('/')
  const cases = []
  const browserErrors = []
  page.on('pageerror', error => browserErrors.push(error.message))
  const check = (value, message) => { if (!value) throw new Error(message) }
  const select = async (scope, label, option, searchText) => {
    const combobox = scope.getByRole('combobox', { name: new RegExp(label + '$') })
    await combobox.click()
    if (searchText) await combobox.fill(searchText)
    await page.locator('.ant-select-dropdown:visible .ant-select-item-option').filter({ hasText: option }).first().click()
  }
  const selectPeriod = async (scope, label, section) => {
    const combobox = scope.getByRole('combobox', { name: new RegExp(label + '$') })
    await combobox.click()
    await combobox.press('Home')
    for (let index = 1; index < section; index += 1) await combobox.press('ArrowDown')
    await combobox.press('Enter')
  }
  const response = async (method, path, action, status) => {
    const [result] = await Promise.all([page.waitForResponse(r => r.request().method() === method && r.url().split('?')[0].split('/').slice(3).join('/').replace(/^/, '/') === path), action()])
    check(result.status() === status, `${method} ${path}: expected ${status}, got ${result.status()}`)
    return result
  }
  const openImport = async () => {
    await page.getByRole('button', { name: '批量导入到课率', exact: true }).click()
    return page.getByRole('dialog', { name: '批量导入到课率', exact: true })
  }
  const fresh = async () => {
    // Full navigation intentionally starts a new independent batch, retaining old
    // batch audit history. Resume is tested separately before confirming.
    await page.goto(base + '/inspections/attendance')
    await page.getByRole('heading', { name: '到课率检查', exact: true }).waitFor()
  }
  await fresh()
  await page.getByText('当前范围暂无到课率记录', { exact: true }).waitFor()
  let drawer = await openImport()
  await select(drawer, '导入目标部门', '学习部')
  const [download] = await Promise.all([page.waitForEvent('download'), drawer.getByRole('button', { name: '下载标准模板' }).click()])
  await download.saveAs(`${output}/downloaded-template.xlsx`)
  check(download.suggestedFilename().endsWith('.xlsx'), 'Wrong download filename')
  await drawer.locator('input[type=file]').setInputFiles(fixture.badFile)
  await drawer.getByText('仅支持无宏的 .xlsx 文件', { exact: true }).waitFor()
  check(!await drawer.getByRole('button', { name: '上传并生成预览' }).isEnabled(), 'Invalid extension enabled upload')
  cases.push('已发布模板真实下载、非 XLSX 文件前端拦截')
  await drawer.locator('input[type=file]').setInputFiles(fixture.validFile)
  const upload = await response('POST', '/api/v1/imports/attendance', () => drawer.getByRole('button', { name: '上传并生成预览' }).click(), 201)
  const batch = await upload.json()
  await drawer.getByText('校验通过', { exact: true }).waitFor()
  await drawer.getByRole('cell', { name: '000001', exact: true }).waitFor()
  await drawer.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('button', { name: '保留并关闭', exact: true }).click()
  await drawer.waitFor({ state: 'hidden' })
  drawer = await openImport()
  await drawer.getByText('校验通过', { exact: true }).waitFor()
  cases.push('真实上传和两行预览、学号前导零、关闭后恢复未确认批次')
  await drawer.getByRole('button', { name: '确认导入 2 条记录' }).click()
  await response('POST', `/api/v1/imports/${batch.id}/confirm`, () => page.getByRole('button', { name: '确认写入草稿记录' }).click(), 200)
  await drawer.getByText('已成功导入 2 条草稿记录', { exact: true }).waitFor()
  await drawer.getByRole('button', { name: 'Close', exact: true }).click()
  await drawer.waitFor({ state: 'hidden' })
  await page.getByRole('cell', { name: 'E2E student A', exact: true }).waitFor({ timeout: 7000 })
  await page.getByRole('cell', { name: 'E2E student B', exact: true }).waitFor()
  cases.push('确认真实入库后全部部门列表立即刷新')
  await page.reload()
  await page.getByRole('cell', { name: 'E2E student A', exact: true }).waitFor()
  cases.push('重载后导入结果持久化')

  await page.getByRole('button', { name: '新增记录', exact: true }).click()
  drawer = page.getByRole('dialog', { name: '新增到课率记录' })
  await drawer.getByRole('button', { name: /取\s*消/ }).click()
  const rowA = () => page.getByRole('row').filter({ has: page.getByRole('cell', { name: 'E2E student A', exact: true }) })
  await rowA().getByRole('button', { name: '编辑', exact: true }).click()
  drawer = page.getByRole('dialog', { name: '编辑到课率记录' })
  await drawer.locator('#course-record_studentId').waitFor()
  await drawer.getByText(/E2E student A（000001，E2E class/).waitFor()
  await drawer.getByLabel('备注').fill('E2E edited')
  await drawer.getByLabel('修改原因').fill('E2E correction')
  const pattern = '**/api/v1/inspections/*'
  const fail = route => route.request().method() === 'PATCH' ? route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ code:'INTERNAL_ERROR', message:'服务暂时不可用' }) }) : route.continue()
  await page.route(pattern, fail)
  await drawer.getByRole('button', { name: '保存修改' }).click()
  await drawer.getByText('保存失败，请稍后重试。', { exact: true }).waitFor()
  check(await drawer.getByLabel('备注').inputValue() === 'E2E edited', 'Save failure lost input')
  await page.unroute(pattern, fail)
  await drawer.getByRole('button', { name: '保存修改' }).click()
  await drawer.waitFor({ state: 'hidden' })
  await rowA().getByRole('button', { name: '编辑', exact: true }).click()
  drawer = page.getByRole('dialog', { name: '编辑到课率记录' })
  await drawer.getByLabel('备注').waitFor()
  check(await drawer.getByLabel('备注').inputValue() === 'E2E edited', 'Edited value did not persist')
  await drawer.getByRole('button', { name: /取\s*消/ }).click()
  await page.getByRole('row').filter({ hasText: 'E2E student B' }).getByRole('button', { name: '编辑', exact: true }).click()
  drawer = page.getByRole('dialog', { name: '编辑到课率记录' })
  await drawer.locator('#course-record_studentId').waitFor()
  await drawer.getByText(/E2E student B（000002，E2E class/).waitFor()
  await drawer.getByRole('button', { name: /取\s*消/ }).click()
  cases.push('新增关闭→首次编辑、保存 500 保留输入重试、重开持久化、A/B 不串值')

  await page.getByRole('button', { name: '新增记录', exact: true }).click()
  drawer = page.getByRole('dialog', { name: '新增到课率记录' })
  await drawer.getByRole('button', { name: '保存草稿' }).click()
  await drawer.getByText('请填写或选择此项', { exact: true }).first().waitFor()
  await select(drawer, '录入学期', '浏览器回归学期')
  await select(drawer, '录入周次', fixture.weekStart)
  await drawer.getByText(/本周违纪计入倍数为 [12]；填写实际旷课学时后自动显示计入结果。/).waitFor()
  await select(drawer, '目标部门', '学习部')
  await select(drawer, '学生班级', 'E2E class')
  await select(drawer, '学生', 'E2E student A')
  await drawer.getByLabel('检查日期').fill(fixture.date)
  await drawer.getByLabel('检查日期').press('Enter')
  await select(drawer, '课程', 'E2E course', 'E2E co')
  await select(drawer, '教室', 'E2E building 101')
  await selectPeriod(drawer, '开始节次', 1)
  await selectPeriod(drawer, '结束节次', 2)
  const actualHours=drawer.getByRole('spinbutton',{name:'实际旷课学时（按节次自动计算）'})
  if(await actualHours.inputValue()!=='2'||await actualHours.isEnabled())throw new Error('attendance actual hours must be calculated from the selected sections')
  await drawer.getByLabel('备注').fill('E2E manual')
  await drawer.getByText(/实际旷课 2 学时；本周按 [12] 倍计入违纪，共 [24] 学时。/).waitFor()
  await drawer.getByLabel('检查时间').fill('10:00:00')
  await drawer.getByLabel('检查时间').press('Enter')
  const created = await response('POST', '/api/v1/inspections', () => drawer.getByRole('button', { name: '保存草稿' }).click(), 201)
  await drawer.waitFor({ state:'hidden' })
  const login = await page.context().request.post(base + '/api/v1/auth/login', { data: { loginName:'browser-admin', password:fixture.authPassword } })
  check(login.status()===200,'Isolated admin login failed')
  const authHeaders={Authorization:'Bearer '+(await login.json()).accessToken}
  const createdInput=created.request().postDataJSON()
  const mismatched=await page.context().request.post(base + '/api/v1/inspections',{headers:authHeaders,data:{...createdInput,details:{...createdInput.details,absenceHours:1}}})
  const mismatchBody=await mismatched.json()
  check(mismatched.status()===422&&mismatchBody.code==='VALIDATION_FAILED'&&mismatchBody.details?.some(item=>item.path==='details.absenceHours'&&item.code==='PERIOD_HOURS_MISMATCH'),'Mismatched section hours were accepted by the API')
  cases.push('节次自动折算实际学时，伪造不一致学时返回字段级 422')
  const manual = page.getByRole('row').filter({ hasText: '手工录入' })
  await manual.getByRole('cell', { name: /^[12] 倍$/ }).waitFor()
  await manual.getByRole('button', { name:'删除', exact:true }).click()
  let dialog = page.getByRole('dialog', { name:'确认删除 1 条到课率草稿？' })
  await dialog.getByRole('button', { name:/取\s*消/ }).click()
  await manual.getByRole('button', { name:'删除', exact:true }).click()
  dialog = page.getByRole('dialog', { name:'确认删除 1 条到课率草稿？' })
  await dialog.getByLabel('删除原因').fill('E2E delete')
  await dialog.getByRole('button', { name:'确认删除', exact:true }).click()
  await dialog.waitFor({ state:'hidden' })
  await manual.waitFor({ state:'hidden' })
  cases.push('手工新增必填校验、真实保存、删除取消与确认')
  for (const name of ['E2E student A', 'E2E student B']) await page.getByRole('row').filter({ hasText:name }).getByRole('checkbox').check()
  await page.getByRole('button', { name:'批量删除（2）' }).click()
  dialog = page.getByRole('dialog', { name:'确认删除 2 条到课率草稿？' })
  await dialog.getByLabel('删除原因').fill('E2E bulk delete')
  await dialog.getByRole('button', { name:'确认删除', exact:true }).click()
  await dialog.waitFor({ state:'hidden' })
  await page.getByText('当前范围暂无到课率记录', { exact:true }).waitFor()
  cases.push('两条草稿批量删除及列表空态')

  drawer = await openImport()
  await select(drawer, '导入目标部门', '学习部')
  await drawer.locator('input[type=file]').setInputFiles(fixture.validFile)
  const secondUpload = await response('POST', '/api/v1/imports/attendance', () => drawer.getByRole('button', {name:'上传并生成预览'}).click(), 201)
  const secondBatch = await secondUpload.json()
  await drawer.getByRole('button', {name:'确认导入 2 条记录'}).click()
  await response('POST', `/api/v1/imports/${secondBatch.id}/confirm`, () => page.getByRole('button', {name:'确认写入草稿记录'}).click(), 200)
  await drawer.getByText('已成功导入 2 条草稿记录', {exact:true}).waitFor()
  await drawer.getByRole('button', {name:'Close',exact:true}).click()
  await drawer.waitFor({state:'hidden'})
  await page.getByRole('cell', {name:'E2E student A',exact:true}).waitFor({timeout:7000})
  cases.push('连续第二次导入、不重开预览直接确认后全部部门列表刷新')
  drawer = await openImport()
  await select(drawer, '导入目标部门', '学习部')
  await drawer.locator('input[type=file]').setInputFiles(fixture.invalidFile)
  await drawer.getByRole('button', { name:'上传并生成预览' }).click()
  await drawer.getByText('存在错误行，当前批次不能确认', { exact:true }).waitFor()
  check(!await drawer.getByRole('button', { name:'确认导入 1 条记录' }).isEnabled(), 'Invalid batch allowed confirmation')
  await drawer.getByText('仅错误', { exact:true }).click()
  await drawer.getByRole('cell', { name:'UNKNOWN', exact:true }).waitFor()
  await page.screenshot({ path:`${output}/attendance-invalid.png`, fullPage:true })
  cases.push('真实错误行预览、仅错误筛选、整批确认拦截')
  await drawer.getByRole('button', {name:'Close',exact:true}).click()
  await page.getByRole('button', {name:'保留并关闭',exact:true}).click()
  await drawer.waitFor({state:'hidden'})
  const submittedRow = page.getByRole('row').filter({has:page.getByRole('cell',{name:'E2E student A',exact:true})})
  const snapshotMultiplier = Number((await submittedRow.getByRole('cell',{name:/^[12] 倍$/}).innerText()).match(/[12]/)?.[0])
  check(snapshotMultiplier===1||snapshotMultiplier===2,'Imported row has no penalty snapshot')
  await submittedRow.getByRole('checkbox').check()
  await page.getByRole('button',{name:'提交所选草稿（1）'}).click()
  dialog=page.getByRole('dialog',{name:'确认提交所选记录？'})
  await dialog.getByRole('button',{name:'确认提交'}).click()
  await dialog.waitFor({state:'hidden'})
  await page.getByRole('button',{name:'检查提交批次'}).click()
  let batches=page.getByRole('dialog',{name:'检查提交批次'})
  await batches.getByRole('button',{name:'退回',exact:true}).click()
  dialog=page.getByRole('dialog',{name:'退回提交批次'})
  await dialog.getByLabel('退回原因').fill('核对快照')
  await dialog.getByRole('button',{name:'确认退回'}).click()
  await dialog.waitFor({state:'hidden'})
  await batches.locator('.ant-table-row-expand-icon').first().click()
  await batches.getByRole('button',{name:/更正第\s*1\s*条记录/}).click()
  await batches.waitFor({state:'hidden'})
  drawer=page.getByRole('dialog',{name:'编辑到课率记录'})
  await drawer.getByText(`实际旷课 2 学时；原记录按 ${snapshotMultiplier} 倍计入违纪，共 ${snapshotMultiplier*2} 学时。`,{exact:true}).waitFor()
  await drawer.getByRole('button',{name:/取\s*消/}).click()
  cases.push('退回记录编辑时按已存快照显示违纪计入学时')
  check(browserErrors.length === 0, 'Uncaught browser error: ' + browserErrors.join('; '))
  return { cases, browserErrors, faultInjection:['编辑 PATCH HTTP 500'], browserVersion:page.context().browser().version() }
}
